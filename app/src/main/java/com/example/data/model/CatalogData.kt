            "toilet paper" to listOf("papel higienico"),
            "chocolate" to listOf("chocolate"),
            "cookie" to listOf("biscoito", "cookies"),
            "cookies" to listOf("biscoito", "cookies")
        )

        val searchTerms = mutableListOf(clean)
        englishSynonyms[clean]?.let { searchTerms.addAll(it) }

        val results = mutableListOf<CatalogItem>()
        for (term in searchTerms) {
            val startsWith = ITEMS.filter { it.name.normalizeForSearch().startsWith(term) }
            val contains = ITEMS.filter {
                val norm = it.name.normalizeForSearch()
                !norm.startsWith(term) && (norm.contains(" $term") || norm.contains(term))
            }
            results.addAll(startsWith)
            results.addAll(contains)
        }

        return results.distinctBy { it.name }.take(12)
    }

